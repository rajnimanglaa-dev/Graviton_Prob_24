CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY,
  public_id VARCHAR(32) NOT NULL UNIQUE,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  phone_number VARCHAR(20) NULL UNIQUE,
  role ENUM('citizen', 'administrator', 'driver') NOT NULL DEFAULT 'citizen',
  ward VARCHAR(120) NULL,
  avatar_url VARCHAR(2048) NULL,
  points INT UNSIGNED NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_users_role (role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vehicles (
  id CHAR(36) PRIMARY KEY,
  public_id VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(160) NOT NULL,
  registration_number VARCHAR(60) NOT NULL UNIQUE,
  vehicle_type VARCHAR(80) NOT NULL,
  capacity_kg DECIMAL(10,2) NOT NULL,
  current_load_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  status ENUM('available', 'assigned', 'on_route', 'maintenance', 'inactive') NOT NULL DEFAULT 'available',
  driver_user_id CHAR(36) NULL,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_vehicle_driver FOREIGN KEY (driver_user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT chk_vehicle_capacity CHECK (capacity_kg > 0),
  CONSTRAINT chk_vehicle_load CHECK (current_load_kg >= 0 AND current_load_kg <= capacity_kg),
  INDEX idx_vehicles_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS waste_reports (
  id CHAR(36) PRIMARY KEY,
  public_id VARCHAR(32) NOT NULL UNIQUE,
  reporter_user_id CHAR(36) NULL,
  source ENUM('website', 'sms') NOT NULL,
  idempotency_key VARCHAR(128) NULL UNIQUE,
  title VARCHAR(240) NOT NULL,
  description TEXT NULL,
  image_url VARCHAR(2048) NULL,
  image_storage_key VARCHAR(512) NULL,
  location_label VARCHAR(500) NOT NULL,
  ward VARCHAR(120) NULL,
  latitude DECIMAL(10,7) NULL,
  longitude DECIMAL(10,7) NULL,
  category VARCHAR(80) NULL,
  severity ENUM('small', 'medium', 'large') NULL,
  priority ENUM('low', 'medium', 'high', 'critical') NOT NULL DEFAULT 'medium',
  priority_score TINYINT UNSIGNED NULL,
  confidence DECIMAL(5,4) NULL,
  estimated_weight_kg DECIMAL(10,2) NULL,
  status ENUM('pending_verification', 'verified', 'rejected', 'assigned', 'on_the_way', 'arrived', 'collected', 'resolved') NOT NULL DEFAULT 'pending_verification',
  verified_by_user_id CHAR(36) NULL,
  verified_at TIMESTAMP NULL,
  rejection_reason VARCHAR(500) NULL,
  assigned_vehicle_id CHAR(36) NULL,
  collection_started_at TIMESTAMP NULL,
  resolved_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_report_user FOREIGN KEY (reporter_user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_report_verified_by FOREIGN KEY (verified_by_user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_report_vehicle FOREIGN KEY (assigned_vehicle_id) REFERENCES vehicles(id) ON DELETE SET NULL,
  CONSTRAINT chk_report_coordinates CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude IS NOT NULL AND longitude IS NOT NULL)),
  INDEX idx_reports_status_priority (status, priority),
  INDEX idx_reports_source_created (source, created_at),
  INDEX idx_reports_coordinates (latitude, longitude),
  INDEX idx_reports_reporter (reporter_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ai_analyses (
  id CHAR(36) PRIMARY KEY,
  report_id CHAR(36) NOT NULL UNIQUE,
  provider VARCHAR(40) NOT NULL DEFAULT 'xai',
  model VARCHAR(100) NOT NULL,
  status ENUM('pending', 'completed', 'failed', 'not_available') NOT NULL DEFAULT 'pending',
  waste_category VARCHAR(80) NULL,
  severity ENUM('small', 'medium', 'large') NULL,
  priority ENUM('low', 'medium', 'high', 'critical') NULL,
  visible_materials JSON NULL,
  visible_quantity_indicators JSON NULL,
  environmental_concerns JSON NULL,
  explanation TEXT NULL,
  recommended_action TEXT NULL,
  confidence DECIMAL(5,4) NULL,
  raw_response JSON NULL,
  error_message VARCHAR(1000) NULL,
  analyzed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_ai_report FOREIGN KEY (report_id) REFERENCES waste_reports(id) ON DELETE CASCADE,
  INDEX idx_ai_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS route_assignments (
  id CHAR(36) PRIMARY KEY,
  public_id VARCHAR(32) NOT NULL UNIQUE,
  vehicle_id CHAR(36) NOT NULL,
  status ENUM('planned', 'active', 'completed', 'cancelled') NOT NULL DEFAULT 'planned',
  optimisation_provider VARCHAR(80) NOT NULL,
  total_distance_meters DECIMAL(12,2) NOT NULL DEFAULT 0,
  total_duration_seconds INT UNSIGNED NOT NULL DEFAULT 0,
  capacity_used_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  capacity_available_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  route_geometry JSON NULL,
  optimisation_summary JSON NULL,
  created_by_user_id CHAR(36) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_route_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id) ON DELETE RESTRICT,
  CONSTRAINT fk_route_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
  INDEX idx_routes_vehicle_status (vehicle_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS route_stops (
  id CHAR(36) PRIMARY KEY,
  route_assignment_id CHAR(36) NOT NULL,
  report_id CHAR(36) NOT NULL,
  stop_sequence INT UNSIGNED NOT NULL,
  planned_weight_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  leg_distance_meters DECIMAL(12,2) NULL,
  leg_duration_seconds INT UNSIGNED NULL,
  status ENUM('planned', 'completed', 'skipped') NOT NULL DEFAULT 'planned',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_stop_route FOREIGN KEY (route_assignment_id) REFERENCES route_assignments(id) ON DELETE CASCADE,
  CONSTRAINT fk_stop_report FOREIGN KEY (report_id) REFERENCES waste_reports(id) ON DELETE RESTRICT,
  CONSTRAINT uq_route_stop_sequence UNIQUE (route_assignment_id, stop_sequence),
  CONSTRAINT uq_route_stop_report UNIQUE (route_assignment_id, report_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS sms_records (
  id CHAR(36) PRIMARY KEY,
  provider_message_id VARCHAR(255) NULL UNIQUE,
  idempotency_key VARCHAR(128) NOT NULL UNIQUE,
  sender_phone_number VARCHAR(20) NOT NULL,
  original_message TEXT NOT NULL,
  extracted_location VARCHAR(500) NULL,
  source ENUM('simulator', 'provider_webhook') NOT NULL,
  report_id CHAR(36) NULL,
  processing_status ENUM('received', 'processed', 'rejected', 'failed', 'duplicate') NOT NULL,
  error_details VARCHAR(1000) NULL,
  received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_sms_report FOREIGN KEY (report_id) REFERENCES waste_reports(id) ON DELETE SET NULL,
  INDEX idx_sms_sender_received (sender_phone_number, received_at),
  INDEX idx_sms_report (report_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS notifications (
  id CHAR(36) PRIMARY KEY,
  user_id CHAR(36) NULL,
  target_role ENUM('citizen', 'administrator', 'driver', 'all') NOT NULL DEFAULT 'all',
  type VARCHAR(80) NOT NULL,
  title VARCHAR(180) NOT NULL,
  message VARCHAR(1000) NOT NULL,
  entity_type VARCHAR(80) NULL,
  entity_id CHAR(36) NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMP NULL,
  CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  INDEX idx_notifications_user_read (user_id, is_read, created_at),
  INDEX idx_notifications_role_read (target_role, is_read, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS report_status_history (
  id CHAR(36) PRIMARY KEY,
  report_id CHAR(36) NOT NULL,
  previous_status VARCHAR(40) NULL,
  new_status VARCHAR(40) NOT NULL,
  note VARCHAR(1000) NULL,
  changed_by_user_id CHAR(36) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_history_report FOREIGN KEY (report_id) REFERENCES waste_reports(id) ON DELETE CASCADE,
  CONSTRAINT fk_history_user FOREIGN KEY (changed_by_user_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_history_report_created (report_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
